// Generates prisma/schema.prisma model Penduduk from config/indikator-mapping.json
// so the ~269 DDP columns stay in sync with the single source-of-truth config.
const fs = require("fs");
const path = require("path");

const mappingPath = path.join(__dirname, "..", "config", "indikator-mapping.json");
const mapping = JSON.parse(fs.readFileSync(mappingPath, "utf8"));

const TYPE_TO_PRISMA = {
  string: "String?",
  int: "Int?",
  float: "Float?",
  date: "DateTime?",
  boolean: "Boolean?",
};

const lines = [];
lines.push(`// AUTO-GENERATED by scripts/build-prisma-schema.js — do not edit by hand.`);
lines.push(`// Edit config/indikator-mapping.json and re-run: node scripts/build-prisma-schema.js`);
lines.push(``);
lines.push(`generator client {`);
lines.push(`  provider = "prisma-client-js"`);
lines.push(`}`);
lines.push(``);
// PostgreSQL is the checked-in production/default schema. SQLite remains an
// explicit zero-setup option for local QA (DB_PROVIDER=sqlite).
const DB_PROVIDER = process.env.DB_PROVIDER || "postgresql";
lines.push(`datasource db {`);
lines.push(`  provider  = "${DB_PROVIDER}"`);
lines.push(`  url       = env("DATABASE_URL")`);
if (DB_PROVIDER === "postgresql") {
  // Neon injects both. Pooled (DATABASE_URL) for runtime; unpooled
  // (DATABASE_URL_UNPOOLED) for migrations — migrate can't run on PgBouncer.
  lines.push(`  directUrl = env("DATABASE_URL_UNPOOLED")`);
}
lines.push(`}`);
lines.push(``);
lines.push(`// Tenant: one village (desapresisi.id subdomain).`);
lines.push(`model Desa {`);
lines.push(`  id        String   @id @default(cuid())`);
lines.push(`  slug      String   @unique // subdomain, e.g. "desa-setu"`);
lines.push(`  nama      String`);
lines.push(`  kodeWilayah String? // official village code used by spatial layers`);
lines.push(`  droneTilePrefix String? // maps-xyz bucket prefix, e.g. 32.01.02.2004`);
lines.push(`  centerLat Float?`);
lines.push(`  centerLng Float?`);
lines.push(`  createdAt DateTime @default(now())`);
lines.push(`  updatedAt DateTime @updatedAt`);
lines.push(`}`);
lines.push(``);
lines.push(`model User {`);
lines.push(`  id        String   @id @default(cuid())`);
lines.push(`  email     String   @unique`);
lines.push(`  name      String?`);
lines.push(`  password  String`);
lines.push(`  desaId    String?  // tenant this user belongs to`);
lines.push(`  role      String   @default("operator") // "operator" | "pemerintah_desa"`);
lines.push(`  createdAt DateTime @default(now())`);
lines.push(`  updatedAt DateTime @updatedAt`);
lines.push(``);
lines.push(`  @@index([desaId])`);
lines.push(`}`);
lines.push(``);
lines.push(`model Penduduk {`);
lines.push(`  id        String   @id @default(cuid())`);
lines.push(`  desaId    String?`);
lines.push(`  createdAt DateTime @default(now())`);
lines.push(`  updatedAt DateTime @updatedAt`);
lines.push(``);

for (const [col, def] of Object.entries(mapping.kolom)) {
  const prismaType = TYPE_TO_PRISMA[def.tipe] || "String?";
  const fieldName = col;
  let extra = "";
  if (col === "abs_id" || col === "nik") extra = " @unique";
  // Ensure at least one space separates long field names from their type.
  const padded = fieldName.length >= 28 ? `${fieldName} ` : fieldName.padEnd(28, " ");
  lines.push(`  ${padded}${prismaType}${extra}`);
}

lines.push(``);
lines.push(`  @@index([desaId])`);
lines.push(`  @@index([nik])`);
lines.push(`  @@index([nkk])`);
lines.push(`  @@index([dusun])`);
lines.push(`  @@index([rw, rt])`);
lines.push(`}`);
lines.push(``);

// --- Spatial building registry ---------------------------------------------
lines.push(`// Digitized physical building. Occupants keep kode_bangunan in Penduduk.`);
lines.push(`model Bangunan {`);
lines.push(`  id            String   @id @default(cuid())`);
lines.push(`  desaId        String?`);
lines.push(`  kode          Int`);
lines.push(`  jenis         String   // \"BERPENGHUNI\" | \"TIDAK_BERPENGHUNI\"`);
lines.push(`  kategori      String?`);
lines.push(`  keterangan    String?`);
lines.push(`  fotoUrl       String?`);
lines.push(`  polygon       String   // GeoJSON polygon coordinates`);
lines.push(`  centroidLat   Float`);
lines.push(`  centroidLng   Float`);
lines.push(`  dusun         String?`);
lines.push(`  rw            Int?`);
lines.push(`  rt            Int?`);
lines.push(`  alamat        String?`);
lines.push(`  createdBy     String?`);
lines.push(`  createdByName String?`);
lines.push(`  createdAt     DateTime @default(now())`);
lines.push(`  updatedAt     DateTime @updatedAt`);
lines.push(``);
lines.push(`  @@unique([desaId, kode])`);
lines.push(`  @@index([desaId])`);
lines.push(`  @@index([desaId, jenis])`);
lines.push(`}`);
lines.push(``);

// --- Updating workflow (T0/T1 snapshots + staging) --------------------------
// data/payload blobs are stored as JSON strings for SQLite portability; switch
// to Json when moving to Postgres.
lines.push(`// Immutable point-in-time baseline (periode T0, T1, ...).`);
lines.push(`model Snapshot {`);
lines.push(`  id        String   @id @default(cuid())`);
lines.push(`  desaId    String?`);
lines.push(`  kode      String   // "T0", "T1", ...`);
lines.push(`  urutan    Int      // 0, 1, 2, ...`);
lines.push(`  label     String?`);
lines.push(`  catatan   String?`);
lines.push(`  jumlah    Int      @default(0)`);
lines.push(`  jumlahBangunan Int @default(0)`);
lines.push(`  changeCount Int    @default(0)`);
lines.push(`  changeSummary String?`);
lines.push(`  changeActors String? // JSON proposer audit summary`);
lines.push(`  createdBy String?`);
lines.push(`  createdByName String?`);
lines.push(`  createdByEmail String?`);
lines.push(`  createdAt DateTime @default(now())`);
lines.push(`  rows      SnapshotPenduduk[]`);
lines.push(`  buildingRows SnapshotBangunan[]`);
lines.push(``);
lines.push(`  @@unique([desaId, kode])`);
lines.push(`  @@unique([desaId, urutan])`);
lines.push(`  @@index([desaId])`);
lines.push(`}`);
lines.push(``);
lines.push(`// Frozen copy of one digitized building inside a snapshot.`);
lines.push(`model SnapshotBangunan {`);
lines.push(`  id         String   @id @default(cuid())`);
lines.push(`  snapshotId String`);
lines.push(`  snapshot   Snapshot @relation(fields: [snapshotId], references: [id], onDelete: Cascade)`);
lines.push(`  kode       Int`);
lines.push(`  jenis      String`);
lines.push(`  data       String`);
lines.push(``);
lines.push(`  @@index([snapshotId])`);
lines.push(`  @@index([kode])`);
lines.push(`}`);
lines.push(``);
lines.push(`// Frozen copy of one Penduduk row inside a snapshot.`);
lines.push(`model SnapshotPenduduk {`);
lines.push(`  id         String   @id @default(cuid())`);
lines.push(`  snapshotId String`);
lines.push(`  snapshot   Snapshot @relation(fields: [snapshotId], references: [id], onDelete: Cascade)`);
lines.push(`  nik        String?`);
lines.push(`  nkk        String?`);
lines.push(`  nama       String?`);
lines.push(`  dusun      String?`);
lines.push(`  data       String   // full record as JSON`);
lines.push(``);
lines.push(`  @@index([snapshotId])`);
lines.push(`  @@index([nik])`);
lines.push(`}`);
lines.push(``);
lines.push(`// Pending change against the live baseline (Data Perubahan Sementara).`);
lines.push(`model StagingChange {`);
lines.push(`  id         String   @id @default(cuid())`);
lines.push(`  desaId     String?`);
lines.push(`  entityType String   @default(\"PENDUDUK\") // \"PENDUDUK\" | \"BANGUNAN\"`);
lines.push(`  groupId    String?  // one building + its occupants`);
lines.push(`  aksi       String   // "CREATE" | "UPDATE" | "DELETE"`);
lines.push(`  pendudukId String?  // target for UPDATE/DELETE`);
lines.push(`  nik        String?`);
lines.push(`  nama       String?`);
lines.push(`  ringkasan  String?`);
lines.push(`  data       String?  // proposed field values as JSON (CREATE/UPDATE)`);
lines.push(`  status     String   @default("PENDING")`);
lines.push(`  createdBy  String?`);
lines.push(`  createdByName String?`);
lines.push(`  createdByEmail String?`);
lines.push(`  createdAt  DateTime @default(now())`);
lines.push(``);
lines.push(`  @@index([status])`);
lines.push(`  @@index([desaId])`);
lines.push(`  @@index([desaId, groupId])`);
lines.push(`}`);
lines.push(``);

// --- Layanan (surat) + Pengaturan desa ---------------------------------------
lines.push(`// Village profile + letterhead settings (single row).`);
lines.push(`model PengaturanDesa {`);
lines.push(`  id         String   @id @default(cuid())`);
lines.push(`  desaId     String?  @unique`);
lines.push(`  namaKepala String?`);
lines.push(`  kopBaris1  String?  // e.g. PEMERINTAH KABUPATEN ...`);
lines.push(`  kopBaris2  String?  // e.g. KECAMATAN ...`);
lines.push(`  kopBaris3  String?  // nama desa`);
lines.push(`  kopBaris4  String?  // alamat lengkap`);
lines.push(`  penutup    String?`);
lines.push(`  disclaimer String?`);
lines.push(`  updatedAt  DateTime @updatedAt`);
lines.push(`}`);
lines.push(``);
lines.push(`// Reusable letter template.`);
lines.push(`model SuratTemplate {`);
lines.push(`  id        String   @id @default(cuid())`);
lines.push(`  desaId    String?`);
lines.push(`  nama      String`);
lines.push(`  kode      String`);
lines.push(`  kategori  String`);
lines.push(`  isi       String   // body with {{placeholder}} tokens`);
lines.push(`  createdAt DateTime @default(now())`);
lines.push(``);
lines.push(`  @@index([desaId])`);
lines.push(`}`);
lines.push(``);
lines.push(`// One issued letter (for the "Surat Keluar" log).`);
lines.push(`model SuratTerbit {`);
lines.push(`  id           String   @id @default(cuid())`);
lines.push(`  desaId       String?`);
lines.push(`  nomor        String`);
lines.push(`  templateId   String?`);
lines.push(`  templateNama String?`);
lines.push(`  pendudukId   String?`);
lines.push(`  namaWarga    String?`);
lines.push(`  nik          String?`);
lines.push(`  keperluan    String?`);
lines.push(`  createdAt    DateTime @default(now())`);
lines.push(``);
lines.push(`  @@index([createdAt])`);
lines.push(`  @@index([desaId])`);
lines.push(`}`);
lines.push(``);

fs.writeFileSync(path.join(__dirname, "..", "prisma", "schema.prisma"), lines.join("\n"));
console.log("prisma/schema.prisma written with", Object.keys(mapping.kolom).length, "Penduduk fields.");
