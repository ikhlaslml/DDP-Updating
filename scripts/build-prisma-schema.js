// Generates prisma/schema.prisma model Penduduk from config/indikator-mapping.json
// so the ~269 DDP columns stay in sync with the single source-of-truth config.
const fs = require("fs");
const path = require("path");

const mappingPath = path.join(__dirname, "..", "config", "indikator-mapping.json");
const mapping = JSON.parse(fs.readFileSync(mappingPath, "utf8"));

const TYPE_TO_PRISMA = {
  string: "String?",
  int: "Int?",
  float: "Float?",
  date: "DateTime?",
  boolean: "Boolean?",
};

const lines = [];
lines.push(`// AUTO-GENERATED by scripts/build-prisma-schema.js — do not edit by hand.`);
lines.push(`// Edit config/indikator-mapping.json and re-run: node scripts/build-prisma-schema.js`);
lines.push(``);
lines.push(`generator client {`);
lines.push(`  provider = "prisma-client-js"`);
lines.push(`}`);
lines.push(``);
lines.push(`datasource db {`);
lines.push(`  // Local dev uses SQLite (zero setup). For production (Vercel), set`);
lines.push(`  // provider = "postgresql" and DATABASE_URL to a Postgres/Supabase URL,`);
lines.push(`  // then run \`npx prisma migrate dev\` again. See README.md.`);
lines.push(`  provider = "sqlite"`);
lines.push(`  url      = env("DATABASE_URL")`);
lines.push(`}`);
lines.push(``);
lines.push(`model User {`);
lines.push(`  id        String   @id @default(cuid())`);
lines.push(`  email     String   @unique`);
lines.push(`  name      String?`);
lines.push(`  password  String`);
lines.push(`  createdAt DateTime @default(now())`);
lines.push(`  updatedAt DateTime @updatedAt`);
lines.push(`}`);
lines.push(``);
lines.push(`model Penduduk {`);
lines.push(`  id        String   @id @default(cuid())`);
lines.push(`  createdAt DateTime @default(now())`);
lines.push(`  updatedAt DateTime @updatedAt`);
lines.push(``);

for (const [col, def] of Object.entries(mapping.kolom)) {
  const prismaType = TYPE_TO_PRISMA[def.tipe] || "String?";
  const fieldName = col;
  let extra = "";
  if (col === "abs_id" || col === "nik") extra = " @unique";
  const padded = fieldName.padEnd(28, " ");
  lines.push(`  ${padded}${prismaType}${extra}`);
}

lines.push(``);
lines.push(`  @@index([nik])`);
lines.push(`  @@index([nkk])`);
lines.push(`  @@index([dusun])`);
lines.push(`  @@index([rw, rt])`);
lines.push(`}`);
lines.push(``);

fs.writeFileSync(path.join(__dirname, "..", "prisma", "schema.prisma"), lines.join("\n"));
console.log("prisma/schema.prisma written with", Object.keys(mapping.kolom).length, "Penduduk fields.");
